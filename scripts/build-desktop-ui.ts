/**
 * Compiles React/Radix/shadcn-style desktop UI as offline assets.
 * Compressed JS/CSS are embedded in the single Node distribution.
 * Usage: node scripts/build-desktop-ui.ts
 */
import { execFileSync } from 'node:child_process';
import { gzipSync } from 'node:zlib';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

export async function buildDesktopUi(repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..')): Promise<void> {
  const uiRoot = join(repoRoot, 'packages', 'desktop-ui');
  const out = join(repoRoot, 'packages', 'node', 'src', 'workspace-assets.generated.ts');
  const temp = mkdtempSync(join(tmpdir(), 'drop-desktop-ui-'));
  try {
    const built = await build({
      entryPoints: [join(uiRoot, 'src', 'main.tsx')],
      platform: 'browser',
      target: ['es2022'],
      format: 'iife',
      jsx: 'automatic',
      bundle: true,
      minify: true,
      sourcemap: false,
      legalComments: 'none',
      write: false,
      logLevel: 'warning',
    });
    const bundle = built.outputFiles[0]?.contents;
    if (!bundle || bundle.length === 0) throw new Error('E_WORKSPACE_BUILD: frontend JavaScript missing');
    const tailwindCli = join(uiRoot, 'node_modules', '@tailwindcss', 'cli', 'dist', 'index.mjs');
    const cssPath = join(temp, 'workspace.css');
    execFileSync(process.execPath, [tailwindCli, '-i', join(uiRoot, 'src', 'styles.css'), '-o', cssPath, '--minify'], {
      cwd: uiRoot,
      encoding: 'utf8',
      stdio: 'pipe',
    });
    const css = readFileSync(cssPath);
    if (!css.length) throw new Error('E_WORKSPACE_BUILD: stylesheet missing');
    const encoded = (b: Uint8Array): string => gzipSync(b, { level: 9 }).toString('base64');
    // Keep generated lines bounded: review tools can read and hash this module
    // in chunks, and git diffs no longer contain single 100-KB lines.
    const chunks = (b: Uint8Array): string => {
      const lines = encoded(b).match(/.{1,96}/g) ?? [];
      return lines.map((value) => "'" + value + "'").join(' +\n  ');
    };
    const next =
      '/** GENERATED by scripts/build-desktop-ui.ts. Do not edit by hand. */\n' +
      'export const workspaceJsGzipBase64 =\n  ' +
      chunks(bundle) +
      ';\n' +
      'export const workspaceCssGzipBase64 =\n  ' +
      chunks(css) +
      ';\n';
    const previous = (() => {
      try {
        return readFileSync(out, 'utf8');
      } catch {
        return '';
      }
    })();
    if (previous !== next) writeFileSync(out, next);
    process.stdout.write(
      'Drop UI: React + Radix built offline (' +
        String(bundle.length) +
        ' JS bytes, ' +
        String(css.length) +
        ' CSS bytes)\n',
    );
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  buildDesktopUi().catch((error: unknown) => {
    process.stderr.write((error instanceof Error ? error.message : 'E_WORKSPACE_BUILD') + '\n');
    process.exitCode = 1;
  });
}
